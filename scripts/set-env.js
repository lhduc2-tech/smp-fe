const fs = require('fs');
const path = require('path');

const getEnvArgs = () => {
  const args = process.argv.slice(2);
  const envArg = args.find(arg => arg.startsWith('--env='));
  return envArg ? envArg.split('=')[1] : null;
};

const envArg = getEnvArgs();
const isStaging = envArg === 'staging';

const dir = path.resolve(__dirname, '..');
const envFile = isStaging ? path.join(dir, '.env.staging') : path.join(dir, '.env');

function parseEnv(filePath) {
  if (!fs.existsSync(filePath)) {
    console.warn(`WARNING: File ${filePath} not found. Using default empty env.`);
    return {};
  }
  const content = fs.readFileSync(filePath, 'utf-8');
  return content.split('\n').reduce((acc, line) => {
    const match = line.match(/^\s*([\w]+)\s*=\s*(.*)?\s*$/);
    if (match) {
      let val = match[2];
      if (val && (val.startsWith('"') || val.startsWith("'"))) {
        val = val.substring(1, val.length - 1); // remove quotes if any
      }
      acc[match[1]] = val;
    }
    return acc;
  }, {});
}

const envConfig = parseEnv(envFile);
const baseUrl = envConfig.API_BASE_URL || 'http://localhost:8082';

const targetPath = path.join(dir, 'src/environments/environment.ts');
const targetDevPath = path.join(dir, 'src/environments/environment.development.ts');

const envConfigFile = `// Auto-generated by set-env.js
export const environment = {
  // Backend API Configuration
  api: {
    baseUrl: '${baseUrl}',
    contextPath: '/sales',
    version: 'api/v1'
  },

  // Staff API Endpoints
  staffApi: {
    basePath: '/private/api/v1/staffs'
  },

  // Pagination
  pagination: {
    defaultPageSize: 10,
    defaultSortBy: 'createdAt',
    defaultSortDir: 'desc'
  }
};

export function getApiUrl(endpoint: string): string {
  return \`\${environment.api.baseUrl}\${environment.api.contextPath}\${endpoint}\`;
}
`;

fs.writeFileSync(targetPath, envConfigFile);
console.log(`[Script] Generated ${targetPath} using ${isStaging ? '.env.staging' : '.env'}`);

// Also generate environment.development.ts just in case Angular uses it
if (!isStaging) {
  fs.writeFileSync(targetDevPath, envConfigFile);
}
